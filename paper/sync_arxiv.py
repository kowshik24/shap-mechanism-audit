"""
Regenerate paper/main.tex (single-column preprint) from paper/ieee_bigdata/main.tex so the two
versions never drift. Edit the IEEE source, then run: python paper/sync_arxiv.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
src = (HERE / 'ieee_bigdata' / 'main.tex').read_text()

PREAMBLE = r"""\documentclass[11pt]{article}

\usepackage[margin=1in]{geometry}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{amsmath}
\usepackage{amssymb}
\usepackage[numbers,sort&compress]{natbib}
\usepackage{caption}
\usepackage{subcaption}
\usepackage[hidelinks]{hyperref}
\usepackage[capitalise,nameinlink]{cleveref}
\crefname{figure}{Fig.}{Figs.}
\Crefname{figure}{Fig.}{Figs.}
\crefname{table}{Table}{Tables}
\crefname{section}{Section}{Sections}
\crefname{equation}{Eq.}{Eqs.}

\graphicspath{{figures/}}

% GENERATED by paper/sync_arxiv.py from ieee_bigdata/main.tex -- do not edit by hand.

\begin{document}
"""

# body starts at \title; drop the IEEE preamble
body = src[src.index(r'\title{'):]

# author block
body = re.sub(r'\\author\{\\IEEEauthorblockN\{(.*?)\}\s*\\IEEEauthorblockA\{(.*?)\\\\\s*(.*?)\}\}',
              r'\\author{\1 \\\\ \\small \2 \\\\ \\small \\texttt{\3}}\n\\date{}', body, flags=re.S)
# keywords
body = body.replace(r'\begin{IEEEkeywords}', r'\noindent\textbf{Keywords:} ')
body = body.replace(r'\end{IEEEkeywords}', '')
# two-column floats become ordinary floats
body = re.sub(r'\\(begin|end)\{(figure|table)\*\}', r'\\\1{\2}', body)
# one IEEE column (3.5in) is about 0.55 of the single-column text width; keep figures that size
body = re.sub(r'width=([\d.]*)\\columnwidth',
              lambda m: f'width={float(m.group(1) or 1) * 0.55:.2f}\\textwidth', body)
body = re.sub(r'\\begin\{(figure|table)\}\[t\]', r'\\begin{\1}[htbp]', body)
# paths relative to paper/
body = body.replace(r'\input{tables/', r'\input{ieee_bigdata/tables/')
body = body.replace(r'\bibliographystyle{IEEEtran}', r'\bibliographystyle{plainnat}')
body = body.replace(r'\bibliography{../refs}', r'\bibliography{refs}')

assert 'IEEE' not in body.replace('IEEE Access', '').replace('IEEE International', ''), 'unconverted IEEE macro'
(HERE / 'main.tex').write_text(PREAMBLE + '\n' + body)
print('wrote', HERE / 'main.tex')
